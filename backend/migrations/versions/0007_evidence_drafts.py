"""Evidence review history and editable document draft revisions."""
from alembic import op

revision = "0007"
down_revision = "0006"


def upgrade():
  op.execute("""
    ALTER TABLE law.evidence_items
      ADD COLUMN purpose text NOT NULL DEFAULT '',
      ADD COLUMN revision integer NOT NULL DEFAULT 1 CHECK (revision > 0),
      ADD COLUMN ai_analysis_id bigint REFERENCES law.case_analyses(id);
    ALTER TABLE law.evidence_items DROP CONSTRAINT evidence_items_status_check;
    ALTER TABLE law.evidence_items ADD CONSTRAINT evidence_items_status_check
      CHECK (status IN ('draft', 'withdrawn', 'ai_analyzing', 'ai_passed', 'ai_failed',
                       'lawyer_pending', 'lawyer_rejected', 'lawyer_approved'));
    ALTER TABLE law.evidence_items ALTER COLUMN status SET DEFAULT 'draft';
    CREATE TABLE law.material_events (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      case_id bigint NOT NULL,
      material_id bigint NOT NULL,
      actor_id bigint NOT NULL REFERENCES law.users(id),
      action varchar(20) NOT NULL,
      revision integer NOT NULL,
      comment text NOT NULL DEFAULT '',
      snapshot jsonb NOT NULL,
      created_at timestamptz NOT NULL DEFAULT now(),
      FOREIGN KEY (material_id, case_id) REFERENCES law.evidence_items(id, case_id)
    );
    CREATE INDEX material_events_history_idx ON law.material_events(material_id, id);
    CREATE TABLE law.document_draft_revisions (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      case_id bigint NOT NULL,
      analysis_id bigint NOT NULL,
      revision integer NOT NULL CHECK (revision > 0),
      title varchar(200) NOT NULL,
      body text NOT NULL,
      created_by bigint NOT NULL REFERENCES law.users(id),
      created_at timestamptz NOT NULL DEFAULT now(),
      FOREIGN KEY (analysis_id, case_id) REFERENCES law.case_analyses(id, case_id),
      UNIQUE (analysis_id, revision)
    );
    ALTER TABLE law.case_analyses DROP CONSTRAINT case_analyses_analysis_type_check;
    ALTER TABLE law.case_analyses ADD CONSTRAINT case_analyses_analysis_type_check
      CHECK (analysis_type IN ('win_rate', 'case_summary', 'timeline', 'judicial_reasoning',
        'dispute_focus', 'evidence_chain', 'evidence_list', 'material_review',
        'complaint_draft', 'evidence_catalog'));
    DO $$ BEGIN
      IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'law_app') THEN
        GRANT SELECT, INSERT ON law.material_events, law.document_draft_revisions TO law_app;
        REVOKE UPDATE, DELETE ON law.material_events, law.document_draft_revisions FROM law_app;
        GRANT USAGE, SELECT ON SEQUENCE law.material_events_id_seq, law.document_draft_revisions_id_seq TO law_app;
      END IF;
    END $$;
  """)


